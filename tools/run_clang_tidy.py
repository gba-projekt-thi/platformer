#!/usr/bin/env python3
"""clang-tidy for pre-commit that also works in a `git worktree`.

compile_commands.json is generated by the build (post-create.sh) and git-ignored,
so a fresh worktree has none and clang-tidy would walk up to the main checkout's
file, whose absolute paths point at the main checkout's headers. Instead this
wrapper writes a private database for the checkout it runs in:

* the compile_commands.json of this checkout, or else of the main one, with the
  main checkout's root path rewritten to this checkout's root (a no-op in the
  main checkout itself), and
* an entry for every file passed that the build never compiled (headers!),
  copied from a game source's command with `-x c++`, so a header is never
  guessed to be C ("-std=c++23 not allowed with 'C'"),
* `-I<root>/build` (generated headers such as bn_music_items.h) pointing at the
  main checkout's build when this worktree has none.

Usage (from pre-commit): tools/run_clang_tidy.py FILE...
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path


def git(*args):
    out = subprocess.run(["git", *args], check=True, capture_output=True, text=True)
    return out.stdout.strip()


def rewrite_root(text, old_root, new_root):
    """Point every absolute path of a database at another checkout."""
    return text if old_root == new_root else text.replace(old_root, new_root)


def add_missing_entries(db, files, root):
    """Add an entry per file without one, modelled on a game source's command."""
    known = {e["file"] for e in db}
    template = next((e for e in db if e["file"].startswith(f"{root}/game/src/")), None)
    if template is None:
        return db
    args = [template["arguments"][0], "-x", "c++", *template["arguments"][1:-1]]
    out = list(db)
    for f in files:
        path = str(Path(f).resolve())
        if path not in known:
            out.append({**template, "arguments": [*args, path], "file": path})
            known.add(path)
    return out


def main(files):
    root = git("rev-parse", "--show-toplevel")
    main_root = str(Path(git("rev-parse", "--path-format=absolute", "--git-common-dir")).parent)
    candidates = [Path(root) / "compile_commands.json", Path(main_root) / "compile_commands.json"]
    source = next((c for c in candidates if c.is_file() and c.stat().st_size), None)
    if source is None:
        print(
            "clang-tidy: no compile_commands.json in this checkout or the main one.\n"
            "Generate it once with: ./post-create.sh --force",
            file=sys.stderr,
        )
        return 1
    # a database built in this checkout already has its paths
    old_root = root if source == candidates[0] else main_root
    text = rewrite_root(source.read_text(), old_root, root)
    if not Path(root, "build").is_dir():
        # generated headers (bn_*_items.h) only exist where the game was built
        text = text.replace(f"-I{root}/build", f"-I{main_root}/build")
    db = json.loads(text)
    for entry in db:  # the build dir may not exist here (nothing is built)
        entry["directory"] = root
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "compile_commands.json").write_text(
            json.dumps(add_missing_entries(db, files, root))
        )
        return subprocess.run(["clang-tidy", "-p", tmp, "--quiet", *files], cwd=root).returncode


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
