inline constexpr int WORLD_CHAPTER_COUNT = sizeof(WORLDS) / sizeof(WORLDS[0]);

// The chapter to show when a save slot is continued: the intro for a game
// that has not begun (nothing reached, no death, no record), else none.
inline auto chapter_on_continue(const GameState& state) -> const Chapter* {
    const bool fresh = state.level == 0 && state.furthest_level == 0 &&
                       state.deaths == 0 && state.best_time_frames[0] == 0;
    return fresh ? &INTRO : nullptr;
}

// The chapter to show when the door leads on to `next_level`: the next
// world's, the first time the duck gets there (`furthest_level` before the
// advance).
inline auto chapter_on_advance(int furthest_level, int next_level)
    -> const Chapter* {
    if (next_level <= furthest_level) {
        return nullptr;
    }
    for (int world = 1; world < WorldIndex::WORLD_COUNT; ++world) {
        if (WorldIndex::WORLDS[world].start_index == next_level) {
            return &WORLDS[world];
        }
    }
    return nullptr;
}

// A goes to the next page while there is one; on the last it goes on.
inline auto has_next_page(const Chapter& chapter, int page) -> bool {
    return page + 1 < chapter.page_count;
}

